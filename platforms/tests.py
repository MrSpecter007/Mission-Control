class HealthCheckServiceTests(TestCase):

    def setUp(self):
        self.platform = make_platform()

    def test_no_domain_returns_unknown(self):
        check = run_health_check(self.platform)
        self.assertEqual(check.status, HealthStatus.UNKNOWN)
        self.assertIn('No endpoint', check.error_info)

    @patch('platforms.services.requests.get')
    def test_successful_check_marks_healthy(self, mock_get):
        Domain.objects.create(platform=self.platform, hostname='example.com', is_primary=True, ssl_enabled=False, environment='production')
        mock_response = MagicMock()
        mock_response.status_code = 200
        mock_get.return_value = mock_response
        check = run_health_check(self.platform)
        self.assertEqual(check.status, HealthStatus.HEALTHY)
        self.assertEqual(check.http_status, 200)

    @patch('platforms.services.requests.get')
    def test_500_marks_down(self, mock_get):
        Domain.objects.create(platform=self.platform, hostname='example.com', is_primary=True, ssl_enabled=False, environment='production')
        mock_response = MagicMock()
        mock_response.status_code = 500
        mock_get.return_value = mock_response
        check = run_health_check(self.platform)
        self.assertEqual(check.status, HealthStatus.DOWN)

    @patch('platforms.services.requests.get')
    def test_timeout_marks_down(self, mock_get):
        from requests.exceptions import Timeout
        Domain.objects.create(platform=self.platform, hostname='example.com', is_primary=True, ssl_enabled=False, environment='production')
        mock_get.side_effect = Timeout()
        check = run_health_check(self.platform)
        self.assertEqual(check.status, HealthStatus.DOWN)
        self.assertIn('timed out', check.error_info)

    @patch('platforms.services.requests.get')
    def test_connection_error_marks_down(self, mock_get):
        from requests.exceptions import ConnectionError
        Domain.objects.create(platform=self.platform, hostname='example.com', is_primary=True, ssl_enabled=False, environment='production')
        mock_get.side_effect = ConnectionError()
        check = run_health_check(self.platform)
        self.assertEqual(check.status, HealthStatus.DOWN)

    @patch('platforms.services.requests.get')
    def test_ssl_error_marks_down(self, mock_get):
        from requests.exceptions import SSLError
        Domain.objects.create(platform=self.platform, hostname='example.com', is_primary=True, ssl_enabled=True, environment='production')
        mock_get.side_effect = SSLError()
        check = run_health_check(self.platform)
        self.assertEqual(check.status, HealthStatus.DOWN)
        self.assertIn('SSL', check.error_info)

    @patch('platforms.services.requests.get')
    def test_404_marks_degraded(self, mock_get):
        Domain.objects.create(platform=self.platform, hostname='example.com', is_primary=True, ssl_enabled=False, environment='production')
        mock_response = MagicMock()
        mock_response.status_code = 404
        mock_get.return_value = mock_response
        check = run_health_check(self.platform)
        self.assertEqual(check.status, HealthStatus.DEGRADED)

    def test_health_check_saved_to_database(self):
        check = run_health_check(self.platform)
        self.assertEqual(HealthCheck.objects.filter(platform=self.platform).count(), 1)
        self.assertEqual(HealthCheck.objects.get(pk=check.pk).platform, self.platform)

    def test_default_service_name_wagtail(self):
        name, stype = get_default_service_name('wagtail')
        self.assertEqual(name, 'Wagtail Application')

    def test_default_service_name_laravel(self):
        name, stype = get_default_service_name('laravel')
        self.assertEqual(name, 'Laravel Application')


