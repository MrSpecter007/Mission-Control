class WizardTests(AuthenticatedTestCase):

    def _post_step(self, step, data):
        return self.client.post(reverse('platforms:wizard_step', kwargs={'step': step}), data)

    def _get_step(self, step):
        return self.client.get(reverse('platforms:wizard_step', kwargs={'step': step}))

    def test_wizard_start_clears_and_redirects(self):
        session = self.client.session
        session['platform_wizard'] = {'step1': {'name': 'old'}}
        session.save()
        resp = self.client.get(reverse('platforms:wizard_start'))
        self.assertRedirects(resp, reverse('platforms:wizard_step', kwargs={'step': 1}))
        self.assertNotIn('platform_wizard', self.client.session)

    def test_step1_renders(self):
        resp = self._get_step(1)
        self.assertEqual(resp.status_code, 200)

    def test_step1_valid_advances(self):
        resp = self._post_step(1, {
            'name': 'My Platform',
            'slug': 'my-platform',
            'platform_type': 'website',
            'lifecycle_status': 'development',
        })
        self.assertRedirects(resp, reverse('platforms:wizard_step', kwargs={'step': 2}))
        self.assertIn('step1', self.client.session['platform_wizard'])

    def test_step1_empty_name_invalid(self):
        resp = self._post_step(1, {'name': '', 'slug': '', 'platform_type': 'website', 'lifecycle_status': 'development'})
        self.assertEqual(resp.status_code, 200)
        self.assertFormError(resp.context['form'], 'name', 'This field is required.')

    def test_step2_cannot_access_without_step1(self):
        resp = self._get_step(2)
        self.assertRedirects(resp, reverse('platforms:wizard_step', kwargs={'step': 1}))

    def _complete_wizard(self, overrides=None):
        data = {
            'step1': {'name': 'Full Platform', 'slug': 'full-platform', 'platform_type': 'website', 'lifecycle_status': 'development'},
            'step2': {'framework': 'django', 'default_environment': 'development'},
            'step3': {'repo_option': 'none'},
            'step4': {'host_option': 'none'},
            'step5': {'domain_option': 'none'},
            'step6': {'service_name': 'Web App', 'service_type': 'web', 'service_environment': 'development', 'skip_service': False},
        }
        if overrides:
            data.update(overrides)
        session = self.client.session
        session['platform_wizard'] = {
            'step1': data['step1'],
            'step2': data['step2'],
            'step3': data['step3'],
            'step4': data['step4'],
            'step5': data['step5'],
            'step6': data['step6'],
        }
        session.save()
        return self.client.post(reverse('platforms:wizard_complete'))

    def test_wizard_completion_creates_platform(self):
        resp = self._complete_wizard()
        self.assertEqual(Platform.objects.filter(slug='full-platform').count(), 1)
        p = Platform.objects.get(slug='full-platform')
        self.assertRedirects(resp, reverse('platforms:platform_detail', kwargs={'slug': p.slug}))

    def test_wizard_completion_creates_service(self):
        self._complete_wizard()
        p = Platform.objects.get(slug='full-platform')
        self.assertEqual(p.services.count(), 1)
        self.assertEqual(p.services.first().name, 'Web App')

    def test_wizard_completion_without_repo(self):
        self._complete_wizard()
        p = Platform.objects.get(slug='full-platform')
        self.assertEqual(p.repositories.count(), 0)

    def test_wizard_completion_without_host(self):
        self._complete_wizard()
        p = Platform.objects.get(slug='full-platform')
        self.assertIsNone(p.services.first().host)

    def test_wizard_completion_without_domain(self):
        self._complete_wizard()
        p = Platform.objects.get(slug='full-platform')
